def svg(name, size=48, glow=None):
    rows = [r for r in ICONS[name].strip("\n").split("\n")]
    h = len(rows)
    w = max(len(r) for r in rows)
    rects = []
    for y, row in enumerate(rows):
        x = 0
        while x < len(row):
            ch = row[x]
            if ch == ".":
                x += 1
                continue
            run = 1
            while x + run < len(row) and row[x + run] == ch:
                run += 1
            rects.append(f'<rect x="{x}" y="{y}" width="{run}" height="1" fill="{PALETTE[ch]}"/>')
            x += run
    style = f' style="filter:drop-shadow(0 0 {glow}px rgba(34,211,238,.55))"' if glow else ""
    return (f'<svg class="px" xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {w} {h}" width="{size}" '
            f'height="{size * h / w:.0f}" shape-rendering="crispEdges"{style}>' + "".join(rects) + "</svg>")
